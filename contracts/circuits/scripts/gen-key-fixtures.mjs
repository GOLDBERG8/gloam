#!/usr/bin/env node
/**
 * Real shield, unshield and transfer proofs made with BOTH key sets, written to
 * contracts/script/KeyCheckProofs.sol. Tests and the mainnet deploy use them to
 * tell the keys apart: a verifier built from the ceremony's final keys accepts
 * the "Final" proofs and rejects the "Dev" ones, and the other way round.
 *
 *   node contracts/circuits/scripts/gen-key-fixtures.mjs
 *
 * Final keys: contracts/ceremony/build/final (release `ceremony-final`).
 * Dev keys:   app/public/circuits (what the testnet pools verify).
 * snarkjs and circomlibjs come from the app's dependencies.
 */
import { readFileSync, writeFileSync } from "fs";
import { createRequire } from "module";
import { fileURLToPath } from "url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const require = createRequire(here("../../../app/package.json"));
const snarkjs = require("snarkjs");
const { buildPoseidon } = require("circomlibjs");

const FINAL = here("../../ceremony/build/final/");
const DEV = here("../../../app/public/circuits/");
const OUT = here("../../script/KeyCheckProofs.sol");

const poseidon = await buildPoseidon();
const H3 = (a, b, c) => poseidon.F.toObject(poseidon([a, b, c]));

// shield: a 0.001 ETH note; commitment = Poseidon(secret, amount, asset)
const secret = 12345678901234567890n;
const amount = 1000000000000000n;
const shieldInput = { commitment: H3(secret, amount, 0n).toString(), amount: amount.toString(), asset: "0", secret: secret.toString() };
const inputs = {
  shield: shieldInput,
  unshield: JSON.parse(readFileSync(here("../fixtures/real-input.json"), "utf8")),
  transfer: JSON.parse(readFileSync(here("../fixtures/transfer-input.json"), "utf8")),
};

async function prove(circuit, dir) {
  const wasm = `${dir}${circuit}.wasm`;
  const zkey = `${dir}${circuit}_final.zkey`;
  // the verification key read from the zkey itself, so the check cannot drift from it
  const vkey = await snarkjs.zKey.exportVerificationKey(zkey);
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(inputs[circuit], wasm, zkey);
  if (!(await snarkjs.groth16.verify(vkey, publicSignals, proof))) throw new Error(`${circuit} proof does not verify (${dir})`);
  const call = JSON.parse(`[${await snarkjs.groth16.exportSolidityCallData(proof, publicSignals)}]`);
  return { a: call[0], b: call[1], c: call[2], pub: call[3], delta: vkey.vk_delta_2[0][0] };
}

const fn = (name, p) => {
  const big = (h) => BigInt(h).toString();
  const pub = p.pub.map(big);
  return `    function ${name}() internal pure returns (bytes memory proof, uint256[] memory pub) {
        uint256[2] memory a = [uint256(${big(p.a[0])}), ${big(p.a[1])}];
        uint256[2][2] memory b = [
            [uint256(${big(p.b[0][0])}), ${big(p.b[0][1])}],
            [uint256(${big(p.b[1][0])}), ${big(p.b[1][1])}]
        ];
        uint256[2] memory c = [uint256(${big(p.c[0])}), ${big(p.c[1])}];
        proof = abi.encode(a, b, c);
        pub = new uint256[](${pub.length});
${pub.map((v, i) => `        pub[${i}] = ${v};`).join("\n")}
    }`;
};

const out = [];
const deltas = {};
for (const circuit of ["shield", "unshield", "transfer"]) {
  for (const [label, dir] of [["Final", FINAL], ["Dev", DEV]]) {
    const p = await prove(circuit, dir);
    deltas[`${circuit}${label}`] = p.delta;
    out.push(fn(`${circuit}${label}`, p));
  }
}
const finals = ["shieldFinal", "unshieldFinal", "transferFinal"].map((k) => deltas[k]);
if (new Set(finals).size !== 3) throw new Error("final keys share a delta: not independent ceremony output");
for (const c of ["shield", "unshield", "transfer"]) {
  if (deltas[`${c}Final`] === deltas[`${c}Dev`]) throw new Error(`${c}: final and dev keys are the same`);
}

writeFileSync(
  OUT,
  `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

// Generated by contracts/circuits/scripts/gen-key-fixtures.mjs. Do not edit.

/**
 * Real Groth16 proofs for shield, unshield and transfer, made with the trusted
 * setup's FINAL keys (release ceremony-final, 13 contributors, drand round
 * 6561386) and with the single-party DEV keys the testnet pools use. A verifier
 * that accepts the Final proof and rejects the Dev one holds the ceremony key.
 * Proofs are abi.encode(a, b, c) with b in verifier order, as the IVerifier
 * adapters take them.
 */
library KeyCheckProofs {
${out.join("\n\n")}
}
`,
);
console.log("wrote", OUT);
console.log("final deltas distinct:", finals.map((d) => d.slice(0, 12)).join(" "));
// snarkjs keeps its worker threads open; nothing else is left to do
process.exit(0);
